ALTER TABLE public.dugsiga_users
  ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.dugsiga_password_recovery_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash TEXT NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  email TEXT NOT NULL,
  school_id TEXT NOT NULL,
  account_role TEXT NOT NULL,
  teacher_id TEXT,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT dugsiga_password_recovery_role_valid
    CHECK (LOWER(BTRIM(account_role)) IN ('admin', 'school admin', 'school_admin', 'teacher')),
  CONSTRAINT dugsiga_password_recovery_expiry_valid
    CHECK (expires_at <= created_at + INTERVAL '30 minutes')
);

CREATE INDEX IF NOT EXISTS idx_dugsiga_password_recovery_pending_account
  ON public.dugsiga_password_recovery_tokens
    (email, school_id, account_role, teacher_id, expires_at)
  WHERE consumed_at IS NULL;

ALTER TABLE public.dugsiga_password_recovery_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.dugsiga_password_recovery_tokens FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.dugsiga_password_recovery_tokens TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.dugsiga_password_recovery_tokens_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.dugsiga_password_recovery_account_is_active(
  p_email TEXT,
  p_school_id TEXT,
  p_account_role TEXT,
  p_teacher_id TEXT
)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.dugsiga_users AS u
    WHERE u.email = p_email
      AND u.school_id = p_school_id
      AND u.role = p_account_role
      AND u.teacher_id IS NOT DISTINCT FROM p_teacher_id
      AND COALESCE(u.verified, TRUE)
      AND LOWER(BTRIM(u.role)) IN ('admin', 'school admin', 'school_admin', 'teacher')
      AND (
        LOWER(BTRIM(u.role)) <> 'teacher'
        OR EXISTS (
          SELECT 1
          FROM public.dugsiga_teachers AS t
          WHERE t.id::TEXT = p_teacher_id
            AND t.school_id = p_school_id
            AND LOWER(BTRIM(t.email)) = LOWER(BTRIM(p_email))
            AND UPPER(BTRIM(COALESCE(t.status, ''))) = 'ACTIVE'
        )
      )
  );
$$;

CREATE OR REPLACE FUNCTION public.dugsiga_create_password_recovery(
  p_email TEXT,
  p_school_id TEXT,
  p_account_role TEXT,
  p_teacher_id TEXT,
  p_token_hash TEXT,
  p_expires_at TIMESTAMPTZ
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF p_token_hash !~ '^[0-9a-f]{64}$'
     OR p_expires_at <= NOW()
     OR p_expires_at > NOW() + INTERVAL '30 minutes'
     OR NOT public.dugsiga_password_recovery_account_is_active(
       p_email, p_school_id, p_account_role, p_teacher_id
     ) THEN
    RETURN FALSE;
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended(p_email || E'\x1f' || p_school_id, 0)
  );

  INSERT INTO public.dugsiga_password_recovery_tokens (
    token_hash, email, school_id, account_role, teacher_id, expires_at
  )
  VALUES (
    p_token_hash, p_email, p_school_id, p_account_role, p_teacher_id, p_expires_at
  );
  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.dugsiga_validate_password_recovery(
  p_token_hash TEXT
)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.dugsiga_password_recovery_tokens AS r
    WHERE r.token_hash = p_token_hash
      AND r.consumed_at IS NULL
      AND r.expires_at > NOW()
      AND public.dugsiga_password_recovery_account_is_active(
        r.email, r.school_id, r.account_role, r.teacher_id
      )
  );
$$;

CREATE OR REPLACE FUNCTION public.dugsiga_consume_password_recovery(
  p_token_hash TEXT,
  p_password_hash TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_recovery public.dugsiga_password_recovery_tokens%ROWTYPE;
  v_updated_email TEXT;
BEGIN
  IF p_token_hash !~ '^[0-9a-f]{64}$'
     OR p_password_hash NOT LIKE 'scrypt$%' THEN
    RETURN FALSE;
  END IF;

  SELECT *
  INTO v_recovery
  FROM public.dugsiga_password_recovery_tokens AS r
  WHERE r.token_hash = p_token_hash
  AND r.consumed_at IS NULL
  AND r.expires_at > NOW();

  IF NOT FOUND OR NOT public.dugsiga_password_recovery_account_is_active(
    v_recovery.email,
    v_recovery.school_id,
    v_recovery.account_role,
    v_recovery.teacher_id
  ) THEN
    RETURN FALSE;
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended(v_recovery.email || E'\x1f' || v_recovery.school_id, 0)
  );

  SELECT *
  INTO v_recovery
  FROM public.dugsiga_password_recovery_tokens AS r
  WHERE r.token_hash = p_token_hash
    AND r.consumed_at IS NULL
    AND r.expires_at > NOW()
  FOR UPDATE;

  IF NOT FOUND OR NOT public.dugsiga_password_recovery_account_is_active(
    v_recovery.email,
    v_recovery.school_id,
    v_recovery.account_role,
    v_recovery.teacher_id
  ) THEN
    RETURN FALSE;
  END IF;

  UPDATE public.dugsiga_users AS u
  SET password = p_password_hash,
      session_version = COALESCE(u.session_version, 0) + 1
  WHERE u.email = v_recovery.email
    AND u.school_id = v_recovery.school_id
    AND u.role = v_recovery.account_role
    AND u.teacher_id IS NOT DISTINCT FROM v_recovery.teacher_id
    AND COALESCE(u.verified, TRUE)
    AND (
      LOWER(BTRIM(u.role)) <> 'teacher'
      OR EXISTS (
        SELECT 1
        FROM public.dugsiga_teachers AS t
        WHERE t.id::TEXT = v_recovery.teacher_id
          AND t.school_id = v_recovery.school_id
          AND LOWER(BTRIM(t.email)) = LOWER(BTRIM(v_recovery.email))
          AND UPPER(BTRIM(COALESCE(t.status, ''))) = 'ACTIVE'
      )
    )
  RETURNING u.email INTO v_updated_email;

  IF NOT FOUND THEN
    RETURN FALSE;
  END IF;

  UPDATE public.dugsiga_password_recovery_tokens
  SET consumed_at = NOW()
  WHERE email = v_recovery.email
    AND school_id = v_recovery.school_id
    AND account_role = v_recovery.account_role
    AND teacher_id IS NOT DISTINCT FROM v_recovery.teacher_id
    AND consumed_at IS NULL;

  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.dugsiga_delete_password_recovery(
  p_token_hash TEXT
)
RETURNS VOID
LANGUAGE SQL
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  DELETE FROM public.dugsiga_password_recovery_tokens
  WHERE token_hash = p_token_hash
    AND consumed_at IS NULL;
$$;

